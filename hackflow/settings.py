    for _line in _ENV_FILE.read_text(encoding='utf-8-sig').splitlines():
        _line = _line.strip()
        if not _line or _line.startswith('#') or '=' not in _line:
            continue
        _name, _value = _line.split('=', 1)
        _name, _value = _name.strip(), _value.strip()
